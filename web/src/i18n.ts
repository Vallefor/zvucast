export const catalogs: { en: { [K in MessageKey]: string }; ru: { [K in MessageKey]: string } } = { en, ru }

const STORAGE_KEY = 'zvucast.lang'

/// Нет записи, пустая строка и любой другой язык — английский.
export function storedLang(raw: string | null): Lang {
  return raw === 'ru' ? 'ru' : 'en'
}

export function readLang(): Lang {
  try {
    return storedLang(localStorage.getItem(STORAGE_KEY))
  } catch {
    return 'en'
  }
}

export function writeLang(lang: Lang): void {
  try {
    localStorage.setItem(STORAGE_KEY, lang)
  } catch {
    // Приватный режим: язык живёт до перезагрузки страницы.
  }
}

export function translate(lang: Lang, key: MessageKey, vars?: Vars): string {
  const text = catalogs[lang][key]
  if (!vars) return text
  return text.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = vars[name]
    return value === undefined ? match : String(value)
  })
}

export type Translate = (key: MessageKey, vars?: Vars) => string

/// Подпись счётчика каналов на схеме узла.
export function channelCount(lang: Lang, n: number): string {
  if (lang === 'en') return n === 1 ? `${n} channel` : `${n} channels`
  return `${n} ${chanWord(n)}`
}
